"""Build knowledge/beam/index.yaml from the table files, so it never drifts out of step.

Usage:
    poetry run python helpers/build_index.py          # rewrite index.yaml
    poetry run python helpers/build_index.py --check  # exit 1 if index.yaml is out of date

The hand-written part (dialect, conventions, tables not covered yet) lives in
knowledge/beam/_index_header.yaml. Everything else is taken from the table files:
each table's file, description, and the names of its measures, derived dimensions and
golden queries, and every join, from the
relationships defined on the foreign-key side.

"""

import sys
from pathlib import Path

import yaml

LAYER = Path(__file__).resolve().parent.parent / "knowledge" / "beam"
HEADER = LAYER / "_index_header.yaml"
INDEX = LAYER / "index.yaml"

PREAMBLE = """\
# Read this first to find the table files a question needs, then read those files
# in full before writing SQL.
# Generated by helpers/build_index.py: edit the table files or _index_header.yaml, not this file.

"""


def one_line(text: str) -> str:
    return " ".join(str(text).split())


def build() -> str:
    tables, joins = [], []
    for path in sorted(LAYER.glob("*.yaml")):
        if path in (HEADER, INDEX):
            continue
        doc = yaml.safe_load(path.read_text(encoding="utf-8"))
        entry = {
            "table": doc["table"],
            "file": path.name,
            "description": one_line(doc["description"]),
        }
        for key in ("measures", "derived_dimensions", "golden_queries"):
            names = [item["name"] for item in doc.get(key) or []]
            if names:
                entry[key] = names
        tables.append(entry)
        for rel in doc.get("relationships") or []:
            joins.append(
                f"{doc['table']}.{rel['field']} → {rel['references']} ({rel['relationship_type']})"
            )

    header = HEADER.read_text(encoding="utf-8")
    header = "\n".join(l for l in header.splitlines() if not l.startswith("# ")).strip()
    def dump(data, flow):
        return yaml.safe_dump(
            data, sort_keys=False, allow_unicode=True, width=1000, default_flow_style=flow
        )

    # tables: short lists such as measures stay on one line; joins: one per line
    body = dump({"tables": tables}, None) + "\n" + dump({"joins": joins}, False)
    return PREAMBLE + header + "\n\n" + body


def main() -> int:
    content = build()
    if "--check" in sys.argv:
        current = INDEX.read_text(encoding="utf-8") if INDEX.exists() else ""
        if current != content:
            print("index.yaml is out of date: run poetry run python helpers/build_index.py")
            return 1
        print("index.yaml is up to date")
        return 0
    INDEX.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {INDEX.relative_to(LAYER.parent.parent).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
